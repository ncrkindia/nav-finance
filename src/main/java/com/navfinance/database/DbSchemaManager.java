package com.navfinance.database;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.logging.Level;
import java.util.logging.Logger;

/**
 * Database schema generator and migration controller supporting multiple SQL dialects.
 * <p>
 * Creates tables, foreign keys, constraints, and performance indexes dynamically tailored for
 * embedded H2, MySQL, PostgreSQL, MariaDB, and SQLite.
 * </p>
 *
 * @author Nav Finance Team
 * @version 1.0.0
 */
public class DbSchemaManager {

    private static final Logger LOGGER = Logger.getLogger(DbSchemaManager.class.getName());

    /**
     * Generates standard DDL creation SQL statements tailored to the targeted database dialect.
     *
     * @param dbType target database type
     * @return list of table creation statements
     */
    public static List<String> getTableCreationStatements(DatabaseType dbType) {
        String pkDef;
        String boolDef;
        String tsDef;

        if (dbType == null) dbType = DatabaseType.H2;

        switch (dbType) {
            case POSTGRESQL -> {
                pkDef = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
                boolDef = "BOOLEAN";
                tsDef = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP";
            }
            case SQLITE -> {
                pkDef = "INTEGER PRIMARY KEY AUTOINCREMENT";
                boolDef = "INTEGER";
                tsDef = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP";
            }
            default -> {
                pkDef = "BIGINT AUTO_INCREMENT PRIMARY KEY";
                boolDef = "BOOLEAN";
                tsDef = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP";
            }
        }

        List<String> list = new ArrayList<>();

        // 1. Persons Table
        list.add("CREATE TABLE IF NOT EXISTS persons ("
                + "id " + pkDef + ", "
                + "name VARCHAR(150) NOT NULL, "
                + "contact VARCHAR(50), "
                + "relation VARCHAR(100), "
                + "notes VARCHAR(500), "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ")");

        // 2. Bills Table
        list.add("CREATE TABLE IF NOT EXISTS bills ("
                + "id " + pkDef + ", "
                + "bill_name VARCHAR(150) NOT NULL, "
                + "provider VARCHAR(100), "
                + "default_amount DECIMAL(15,2), "
                + "notes VARCHAR(500), "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ")");

        // 3. EMIs Table
        list.add("CREATE TABLE IF NOT EXISTS emis ("
                + "id " + pkDef + ", "
                + "emi_name VARCHAR(150) NOT NULL, "
                + "bank_lender VARCHAR(100), "
                + "monthly_amount DECIMAL(15,2), "
                + "notes VARCHAR(500), "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ")");

        // 4. Credit Cards Table
        list.add("CREATE TABLE IF NOT EXISTS credit_cards ("
                + "id " + pkDef + ", "
                + "card_name VARCHAR(100) NOT NULL, "
                + "bank VARCHAR(100), "
                + "last_digits VARCHAR(10), "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ")");

        // 5. Payment Modes Table
        list.add("CREATE TABLE IF NOT EXISTS payment_modes ("
                + "id " + pkDef + ", "
                + "mode_name VARCHAR(50) NOT NULL UNIQUE, "
                + "is_system " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "0" : "FALSE") + ", "
                + "created_at " + tsDef + ")");

        // 6. Transactions Table
        list.add("CREATE TABLE IF NOT EXISTS transactions ("
                + "id " + pkDef + ", "
                + "type VARCHAR(10) NOT NULL, "
                + "tx_date DATE NOT NULL, "
                + "is_expected " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "0" : "FALSE") + ", "
                + "amount DECIMAL(15,2) NOT NULL, "
                + "payment_via VARCHAR(50), "
                + "category VARCHAR(100) NOT NULL, "
                + "sub_category VARCHAR(150), "
                + "person_id BIGINT, "
                + "bill_id BIGINT, "
                + "emi_id BIGINT, "
                + "credit_card_id BIGINT, "
                + "notes VARCHAR(1000), "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ", "
                + "FOREIGN KEY (person_id) REFERENCES persons(id) ON DELETE SET NULL, "
                + "FOREIGN KEY (bill_id) REFERENCES bills(id) ON DELETE SET NULL, "
                + "FOREIGN KEY (emi_id) REFERENCES emis(id) ON DELETE SET NULL, "
                + "FOREIGN KEY (credit_card_id) REFERENCES credit_cards(id) ON DELETE SET NULL)");

        // 7. Audit Logs Table
        list.add("CREATE TABLE IF NOT EXISTS audit_logs ("
                + "id " + pkDef + ", "
                + "entity_type VARCHAR(50) NOT NULL, "
                + "entity_id BIGINT, "
                + "action VARCHAR(20) NOT NULL, "
                + "details VARCHAR(2000), "
                + "log_timestamp " + tsDef + ")");

        // 8. Recurring Schedules Table
        list.add("CREATE TABLE IF NOT EXISTS recurring_schedules ("
                + "id " + pkDef + ", "
                + "name VARCHAR(150) NOT NULL, "
                + "type VARCHAR(20) NOT NULL, "
                + "category VARCHAR(100) NOT NULL, "
                + "sub_category VARCHAR(150), "
                + "day_of_month INT NOT NULL, "
                + "amount_type VARCHAR(20) NOT NULL, "
                + "default_amount DECIMAL(15,2) DEFAULT 0.0, "
                + "start_date DATE NOT NULL, "
                + "end_date DATE, "
                + "payment_via VARCHAR(50) DEFAULT 'Net Banking', "
                + "is_auto_pay " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "0" : "FALSE") + ", "
                + "notes VARCHAR(500), "
                + "active " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "1" : "TRUE") + ", "
                + "created_at " + tsDef + ", "
                + "updated_at " + tsDef + ")");

        // 9. Due Payments Table
        list.add("CREATE TABLE IF NOT EXISTS due_payments ("
                + "id " + pkDef + ", "
                + "schedule_id BIGINT, "
                + "title VARCHAR(150) NOT NULL, "
                + "type VARCHAR(20) NOT NULL, "
                + "category VARCHAR(100) NOT NULL, "
                + "sub_category VARCHAR(150), "
                + "due_date DATE NOT NULL, "
                + "expected_amount DECIMAL(15,2) DEFAULT 0.0, "
                + "is_variable " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "0" : "FALSE") + ", "
                + "is_auto_pay " + boolDef + " DEFAULT " + (dbType == DatabaseType.SQLITE ? "0" : "FALSE") + ", "
                + "status VARCHAR(20) DEFAULT 'PENDING', "
                + "settled_amount DECIMAL(15,2) DEFAULT 0.0, "
                + "settled_date DATE, "
                + "settled_via VARCHAR(50), "
                + "transaction_id BIGINT, "
                + "notes VARCHAR(500), "
                + "created_at " + tsDef + ", "
                + "FOREIGN KEY (schedule_id) REFERENCES recurring_schedules(id) ON DELETE SET NULL, "
                + "FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE SET NULL)");

        // 10. Transaction Links Table
        list.add("CREATE TABLE IF NOT EXISTS transaction_links ("
                + "id " + pkDef + ", "
                + "give_tx_id BIGINT NOT NULL, "
                + "return_tx_id BIGINT NOT NULL, "
                + "amount DECIMAL(15,2) NOT NULL, "
                + "notes VARCHAR(500), "
                + "created_at " + tsDef + ", "
                + "FOREIGN KEY (give_tx_id) REFERENCES transactions(id) ON DELETE CASCADE, "
                + "FOREIGN KEY (return_tx_id) REFERENCES transactions(id) ON DELETE CASCADE, "
                + "CONSTRAINT uc_give_return UNIQUE (give_tx_id, return_tx_id))");

        return list;
    }

    /**
     * Initializes all schema tables, constraints, indices, and default catalogs on the given connection.
     *
     * @param conn active live JDBC connection
     * @param dbType target database type
     * @throws SQLException on database execution failure
     */
    public static void initializeSchema(Connection conn, DatabaseType dbType) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            for (String sql : getTableCreationStatements(dbType)) {
                stmt.execute(sql);
            }
        }

        // Create performance indices safely
        createIndexSafely(conn, "idx_tx_date", "transactions", "tx_date");
        createIndexSafely(conn, "idx_tx_type", "transactions", "type");
        createIndexSafely(conn, "idx_tx_category", "transactions", "category");
        createIndexSafely(conn, "idx_due_date", "due_payments", "due_date");
        createIndexSafely(conn, "idx_due_status", "due_payments", "status");
        createIndexSafely(conn, "idx_audit_time", "audit_logs", "log_timestamp");
        createIndexSafely(conn, "idx_link_give", "transaction_links", "give_tx_id");
        createIndexSafely(conn, "idx_link_return", "transaction_links", "return_tx_id");

        // Seed default payment modes across all databases
        seedDefaultPaymentModes(conn, dbType);
    }

    /**
     * Creates an index if it does not already exist, gracefully ignoring dialect variances.
     */
    private static void createIndexSafely(Connection conn, String indexName, String tableName, String column) {
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE INDEX IF NOT EXISTS " + indexName + " ON " + tableName + "(" + column + ")");
        } catch (SQLException e) {
            // Some databases like older MySQL don't support IF NOT EXISTS in CREATE INDEX.
            // Check if index exists or ignore duplicate index errors
            try (Statement stmt = conn.createStatement()) {
                stmt.execute("CREATE INDEX " + indexName + " ON " + tableName + "(" + column + ")");
            } catch (SQLException ignored) {
                // Index already exists
            }
        }
    }

    /**
     * Seeds essential standard payment modes if the payment_modes table is empty.
     */
    private static void seedDefaultPaymentModes(Connection conn, DatabaseType dbType) {
        String countSql = "SELECT COUNT(*) FROM payment_modes";
        try (Statement stmt = conn.createStatement(); ResultSet rs = stmt.executeQuery(countSql)) {
            if (rs.next() && rs.getInt(1) == 0) {
                String[] modes = {"Cash", "UPI", "Paytm", "PhonePe", "Google Pay", "Net Banking", "Credit Card", "Debit Card", "Cheque", "Other"};
                String insertSql = "INSERT INTO payment_modes (mode_name, is_system) VALUES (?, ?)";
                try (PreparedStatement ps = conn.prepareStatement(insertSql)) {
                    for (String m : modes) {
                        ps.setString(1, m);
                        ps.setBoolean(2, true);
                        try {
                            ps.executeUpdate();
                        } catch (SQLException ignored) {}
                    }
                }
                LOGGER.log(Level.INFO, "Seeded standard payment modes into {0}", dbType);
            }
        } catch (SQLException e) {
            LOGGER.log(Level.WARNING, "Failed to check or seed payment modes: {0}", e.getMessage());
        }
    }
}
